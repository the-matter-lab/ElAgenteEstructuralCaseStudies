"""B3LYP-D4/def2-SVP optimisation (Sella) and harmonic thermochemistry with PySCF.

Start geometries: structures generated by the agent in Run 1 (GFN2-xTB level).
  job.py NAME START.xyz SPIN ORDER NTHREADS     ORDER 0 = minimum, 1 = transition state
B3LYP = VWN5 form (b3lyp5). D4 (BJ damping, B3LYP parameters) is included in the
energy, the gradient and, by finite differences of its gradient, the Hessian.
"""
import sys, json, numpy as np
from ase.io import read, write
from ase.calculators.calculator import Calculator, all_changes
from ase.units import Hartree, Bohr
from pyscf import gto, dft, lib
from pyscf.hessian import thermo
from dftd4.interface import DampingParam, DispersionModel
from sella import Sella

name, start, spin, order, nt = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4]), int(sys.argv[5])
lib.num_threads(nt)

def build(sym, pos_A):
    mol = gto.M(atom=[(s, tuple(p)) for s, p in zip(sym, pos_A)], basis='def2-svp', spin=spin, verbose=0)
    mf = dft.UKS(mol) if spin else dft.RKS(mol)
    mf.xc = 'b3lyp5'; mf.grids.level = 4; mf.conv_tol = 1e-10
    return mol, mf.density_fit(auxbasis='def2-universal-jkfit')

def d4(mol, coords=None):
    m = DispersionModel(mol.atom_charges(), mol.atom_coords() if coords is None else coords)
    r = m.get_dispersion(DampingParam(method='b3lyp'), grad=True)
    return float(r['energy']), np.array(r['gradient'])

class B3LYPD4(Calculator):
    implemented_properties = ['energy', 'forces']
    dm = None
    def calculate(self, atoms=None, properties=('energy',), system_changes=all_changes):
        super().calculate(atoms, properties, system_changes)
        mol, mf = build(self.atoms.get_chemical_symbols(), self.atoms.positions)
        e = mf.kernel(dm0=self.dm); assert mf.converged; self.dm = mf.make_rdm1()
        ed, gd = d4(mol); g = mf.nuc_grad_method().kernel() + gd
        self.results = {'energy': (e + ed) * Hartree, 'forces': -g * Hartree / Bohr}

atoms = read(start); atoms.calc = B3LYPD4()
kw = dict(order=order, internal=True, logfile=f'opt/{name}.log', trajectory=f'opt/{name}.traj')
if len(atoms) > 2: opt = Sella(atoms, **kw)
else:
    from ase.optimize import BFGS; opt = BFGS(atoms, logfile=f'opt/{name}.log')
conv = opt.run(fmax=0.01, steps=250)
write(f'opt/{name}.xyz', atoms, comment=f'{name} B3LYP-D4/def2-SVP PySCF+Sella order={order} E={atoms.get_potential_energy()/Hartree:.10f} Eh')

mol, mf = build(atoms.get_chemical_symbols(), atoms.positions)
e = mf.kernel(); ed, gd = d4(mol); g = mf.nuc_grad_method().kernel() + gd
h = mf.Hessian().kernel()                                   # (N,N,3,3)
x0 = mol.atom_coords(); n = mol.natm; hd = np.zeros((n, 3, n, 3)); st = 5e-3
for i in range(n):
    for k in range(3):
        xp = x0.copy(); xp[i, k] += st; xm = x0.copy(); xm[i, k] -= st
        hd[i, k] = (d4(mol, xp)[1] - d4(mol, xm)[1]) / (2 * st)
hd = 0.5 * (hd + hd.transpose(2, 3, 0, 1)); h = h + hd.transpose(0, 2, 1, 3)
fr = thermo.harmonic_analysis(mol, h); t = thermo.thermo(mf, fr['freq_au'], 298.15, 101325)
f = [float(-abs(x.imag) if abs(x.imag) > 0 else x.real) for x in np.asarray(fr['freq_wavenumber'], dtype=complex)]
out = dict(name=name, spin=spin, order=order, converged=bool(conv), steps=int(opt.nsteps), E=float(e) + ed,
           H=float(t['H_tot'][0]) + ed, G=float(t['G_tot'][0]) + ed, max_grad=float(abs(g).max()),
           n_imag=sum(x < 0 for x in f), lowest_freqs=[round(x, 1) for x in sorted(f)[:4]])
json.dump(out, open(f'results/{name}.json', 'w'), indent=1); print(json.dumps(out))
